#!/usr/bin/env python3
"""Generate the native launch wordmark from real Android sans-serif outlines.

Offline generation only; no font parsing, bitmap generation or extra splash in
MainActivity. Requires fonttools and uharfbuzz (pip install fonttools uharfbuzz).
The input font is the Android system Roboto used by PitPitchWordmark, captured
from the Studio device, not substitute/AI artwork. To reproduce:

  adb -s emulator-5554 pull /system/fonts/Roboto-Regular.ttf tmp/validation/pitpitch-startup-Roboto-Regular.ttf
  python3 tmp/tests/generate_startup_branding.py

Input hashes are pinned below. Another device/font revision requires an explicit
art review and updated hashes, not silently different letterforms. Only glyph
outlines are shipped; font copyright/license notices accompany the drawable in
assets/pitpitch-startup-font-licenses.txt. The main Compose wordmark remains text.
"""
import argparse
import hashlib
from pathlib import Path
import xml.etree.ElementTree as ET

import uharfbuzz as hb
from fontTools.misc.transform import Transform
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
ANDROID = 'http://schemas.android.com/apk/res/android'
ET.register_namespace('android', ANDROID)
# Filled in from the captured Android fonts, not from platform-independent substitutes.
ROBOTO_SHA256 = 'd5633ff957d2ecb1ce7716e86e11057091c3526042efe16fe1f65dfc06a65551'

def source(path, expected, index=0):
    body = path.read_bytes()
    if hashlib.sha256(body).hexdigest() != expected:
        raise ValueError(f'Unreviewed font revision: {path}')
    font = TTFont(path, fontNumber=index)
    face = hb.Face(body, index)
    return font, hb.Font(face)


def outlines(font, shaper, text, size, baseline, axes, scale_x=1, skew_x=0, spacing=0):
    """Shape with HarfBuzz and retain the original quadratic/cubic glyph curves."""
    shaper.set_variations(axes)
    units = font['head'].unitsPerEm
    shaper.scale = (units, units)
    buffer = hb.Buffer()
    buffer.add_str(text)
    buffer.guess_segment_properties()
    hb.shape(shaper, buffer)
    glyphs = font.getGlyphSet(location=axes)
    order = font.getGlyphOrder()
    advance = 0
    result = []
    for info, position in zip(buffer.glyph_infos, buffer.glyph_positions):
        if info.codepoint == 0:
            raise ValueError(f'Missing authentic glyph in {text!r}')
        x = advance + position.x_offset * size / units
        y = position.y_offset * size / units
        # Android Paint: x' = textScaleX*x + textSkewX*y (canvas y points down).
        transform = Transform(scale_x * size / units, 0,
                              -skew_x * size / units, -size / units,
                              scale_x * x - skew_x * y, baseline - y)
        glyph = glyphs[order[info.codepoint]]
        bounds = BoundsPen(glyphs)
        glyph.draw(TransformPen(bounds, transform))
        result.append((glyph, glyphs, transform, bounds.bounds, info.cluster))
        advance += position.x_advance * size / units + spacing
    left = min(item[3][0] for item in result)
    right = max(item[3][2] for item in result)
    center = (200 - left - right) / 2
    paths = []
    for glyph, glyphs, transform, _, cluster in result:
        pen = SVGPathPen(glyphs, ntos=lambda value: f'{value:.4f}'.rstrip('0').rstrip('.'))
        centered = Transform(1, 0, 0, 1, center, 0).transform(transform)
        glyph.draw(TransformPen(pen, centered))
        paths.append((pen.getCommands(), cluster))
    return paths


def generate(roboto_path, output):
    roboto, wordmark_font = source(roboto_path, ROBOTO_SHA256)
    vector = ET.Element('vector', {
        f'{{{ANDROID}}}width': '200dp', f'{{{ANDROID}}}height': '80dp',
        f'{{{ANDROID}}}viewportWidth': '200', f'{{{ANDROID}}}viewportHeight': '80'})
    # Exact PitPitchWordmark semantics: sans-serif Black, 28sp, -1sp tracking,
    # scaleX .94, skewX -.18; RaceRed and the existing green. No font-style italic.
    wordmark = outlines(roboto, wordmark_font, 'PitPitch', 28, 49,
                        {'wght': 900, 'wdth': 100, 'ital': 0}, .94, -.18, -1)
    for path, cluster in wordmark:
        ET.SubElement(vector, 'path', {f'{{{ANDROID}}}fillColor': '#E10600' if cluster < 3 else '#008A4B',
                                       f'{{{ANDROID}}}pathData': path})
    ET.indent(vector, space='    ')
    header = ('<?xml version="1.0" encoding="utf-8"?>\n'
              '<!-- Generated by tmp/tests/generate_startup_branding.py from Android Roboto.\n'
              '     Same wordmark typography/colors as PitPitchWordmark; fonts licensed under SIL OFL 1.1. -->\n')
    output.write_text(header + ET.tostring(vector, encoding='unicode') + '\n')
    print(f'Generated {output.relative_to(ROOT)}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--roboto', type=Path, default=ROOT / 'tmp/validation/pitpitch-startup-Roboto-Regular.ttf')
    parser.add_argument('--output', type=Path, default=ROOT / 'app/src/main/res/drawable/pitpitch_startup_wordmark.xml')
    args = parser.parse_args()
    generate(args.roboto, args.output)
